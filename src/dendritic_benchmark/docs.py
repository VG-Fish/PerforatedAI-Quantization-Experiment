"""Generate the current-state guide from the registries that own the truth.

Five hand-written guides drifted apart because each one restated the model
roster, the condition grid, and the CLI options from memory.  This module
renders those sections instead: the roster comes from ``specs``/``model_adapters``,
the validity rules from ``artifacts``/``results``/``statistics``, and the command
reference from the argparse registry in ``cli``.  ``dqb docs --check`` fails when
the checked-in guide no longer matches, so documentation cannot silently rot.

Prose that is genuinely editorial — dated audits, run reports, migration notes —
stays hand-written under ``information/`` and is indexed, not regenerated.
"""

import argparse
import textwrap
from pathlib import Path

from .artifacts import ARTIFACT_MANIFEST_NAME, ARTIFACT_MANIFEST_SCHEMA_VERSION
from .model_adapters import DEFAULT_MODEL_KEYS, model_adapter
from .specs import (
    CONDITION_SPECS,
    MODEL_SPECS,
    condition_supported_by_model,
)
from .statistics import MINIMUM_PAIRED_SEEDS, SIGNIFICANCE_LEVEL

CURRENT_GUIDE_PATH = Path("information") / "CURRENT_GUIDE.md"
GENERATED_BANNER = (
    "<!-- generated by `uv run dqb docs`; edit the registries, not this file -->"
)
_HISTORICAL_INDEX = "information/HISTORICAL_INDEX.md"
_RETENTION_POLICY = "information/RETENTION_POLICY.md"


#: Trailing tokens that end in a period without ending a sentence.
_ABBREVIATIONS = frozenset({"e.g", "i.e", "vs", "etc", "cf", "approx", "no"})


def _first_sentence(text: str | None) -> str:
    if not text:
        return ""
    collapsed = " ".join(text.split())
    index = 0
    while True:
        stop = collapsed.find(". ", index)
        if stop == -1:
            break
        head = collapsed[:stop]
        last_token = head.rsplit(" ", 1)[-1].lower()
        if last_token not in _ABBREVIATIONS:
            return head + "."
        index = stop + 2
    return collapsed


def _summary(text: str | None) -> str:
    """First sentence of the first paragraph, without list continuations."""
    if not text:
        return ""
    paragraph = text.strip().split("\n\n", 1)[0]
    paragraph = paragraph.split("•", 1)[0]
    return _first_sentence(paragraph)


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _format_default(action: argparse.Action) -> str:
    if isinstance(action, argparse._StoreTrueAction | argparse._StoreFalseAction):
        return "flag"
    if action.default is None or action.default is argparse.SUPPRESS:
        return "—"
    return f"`{action.default}`"


def _subparser_action(parser: argparse.ArgumentParser) -> argparse._SubParsersAction:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    raise RuntimeError("the CLI parser has no subcommands")


def _option_rows(
    parser: argparse.ArgumentParser, skip: set[str]
) -> list[tuple[str, str, str]]:
    rows: list[tuple[str, str, str]] = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction | argparse._HelpAction):
            continue
        if action.help == argparse.SUPPRESS:
            continue
        names = set(action.option_strings)
        if names and names <= skip:
            continue
        flags = ", ".join(f"`{name}`" for name in action.option_strings) or (
            f"`{action.dest}`"
        )
        rows.append((flags, _format_default(action), _summary(action.help)))
    return rows


def _options_table(rows: list[tuple[str, str, str]]) -> list[str]:
    if not rows:
        return ["_No command-specific options._", ""]
    lines = ["| option | default | purpose |", "|---|---|---|"]
    lines.extend(
        f"| {flags} | {default} | {_cell(help_text)} |" for flags, default, help_text in rows
    )
    lines.append("")
    return lines


def _model_roster_section() -> list[str]:
    lines = [
        "## Model roster",
        "",
        f"{len(MODEL_SPECS)} models are registered. A bare `dqb run` trains only the "
        f"{len(DEFAULT_MODEL_KEYS)} evidence-backed default models; the rest are "
        "exploratory and need `--models all` or an explicit key.",
        "",
        "| key | display name | dataset | metric | direction | task | default roster |",
        "|---|---|---|---|---|---|---|",
    ]
    for spec in MODEL_SPECS:
        adapter = model_adapter(spec.key)
        lines.append(
            f"| `{spec.key}` | {_cell(spec.display_name)} | {_cell(spec.dataset)} | "
            f"{_cell(spec.metric_name)} | {spec.metric_direction} | {adapter.task_kind} | "
            f"{'yes' if adapter.default_enabled else 'no'} |"
        )
    lines.append("")
    return lines


def _condition_section() -> list[str]:
    lines = [
        "## Condition grid",
        "",
        f"{len(CONDITION_SPECS)} conditions isolate two factors: dendritic "
        "augmentation and quantization. Each condition trains from the checkpoint "
        "named in its source column, so an omitted source condition skips every "
        "condition that depends on it.",
        "",
        "| key | display name | source | bits | mode | dendrites | QAT | quantized |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for spec in CONDITION_SPECS:
        lines.append(
            f"| `{spec.key}` | {_cell(spec.display_name)} | `{spec.source_key}` | "
            f"{spec.bit_width if spec.bit_width is not None else '—'} | "
            f"{spec.quantization_mode or '—'} | "
            f"{'yes' if spec.use_dendrites else 'no'} | "
            f"{'yes' if spec.use_qat else 'no'} | "
            f"{'yes' if spec.quantized else 'no'} |"
        )
    lines.append("")
    unsupported = [
        (spec.key, condition.key)
        for spec in MODEL_SPECS
        for condition in CONDITION_SPECS
        if not condition_supported_by_model(spec.key, condition.key)
    ]
    attempts = len(MODEL_SPECS) * len(CONDITION_SPECS) - len(unsupported)
    lines.extend(
        [
            f"The full matrix is {len(MODEL_SPECS)} models × {len(CONDITION_SPECS)} "
            f"conditions − {len(unsupported)} unsupported pairs = **{attempts} attempts**.",
            "",
        ]
    )
    if unsupported:
        lines.append("Unsupported pairs (skipped rather than trained):")
        lines.append("")
        skipped_models = sorted({model_key for model_key, _ in unsupported})
        for model_key in skipped_models:
            conditions = ", ".join(
                f"`{condition_key}`"
                for model, condition_key in unsupported
                if model == model_key
            )
            lines.append(f"- `{model_key}`: {conditions}")
        lines.append("")
    return lines


def _validity_section() -> list[str]:
    return [
        "## What makes a result reportable",
        "",
        f"Every attempt writes `{ARTIFACT_MANIFEST_NAME}` (schema version "
        f"{ARTIFACT_MANIFEST_SCHEMA_VERSION}) binding one immutable artifact identity "
        "to the SHA-256 of every file it owns. Reporting reads that verdict; it never "
        "infers validity from the presence of files on disk.",
        "",
        "| gate | requirement |",
        "|---|---|",
        "| artifact | manifest is finalized, its identity matches the record, and every "
        "manifest-owned file still hashes to the recorded digest |",
        "| dendritic arm | dendrite audit status is `verified_retained` or "
        "`inherited_verified_retained`, and the manifest agrees with the record |",
        "| quantized arm | the artifact carries the current quantization-evaluation "
        "revision and a `current` quantization status |",
        f"| effect claim | at least {MINIMUM_PAIRED_SEEDS} paired seeds against the dense "
        f"control, significant at p < {SIGNIFICANCE_LEVEL} |",
        "",
        "`compare` writes two audit tables next to the comparison plots: "
        "`dendrite_audit.csv` (per-arm validity, requested vs observed switch schedule, "
        "termination reason, seed-paired effect verdict) and "
        "`dendrite_effect_statistics.csv` (paired seeds, noise floor, mean improvement, "
        "p-value, verdict). A dendritic arm with fewer than "
        f"{MINIMUM_PAIRED_SEEDS} paired seeds is reported as `insufficient_seeds` and "
        "must not be quoted as a win.",
        "",
    ]


def _cli_section() -> list[str]:
    from .cli import build_parser  # imported lazily: cli imports this module

    parser = build_parser()
    shared = {
        name
        for action in parser._actions
        if not isinstance(action, argparse._SubParsersAction)
        for name in action.option_strings
    }
    lines = [
        "## Command reference",
        "",
        "Generated from the argparse registry. `dqb --help` and `dqb <command> --help` "
        "print the same options with their full text.",
        "",
        "### Shared options",
        "",
    ]
    lines.extend(_options_table(_option_rows(parser, skip=set())))
    subparsers = _subparser_action(parser)
    for name, subparser in subparsers.choices.items():
        lines.extend([f"### `dqb {name}`", ""])
        summary = _summary(subparser.description) or _summary(
            subparsers.choices[name].prog
        )
        if summary:
            lines.extend([summary, ""])
        lines.extend(_options_table(_option_rows(subparser, skip=shared)))
    return lines


def _documentation_map_section() -> list[str]:
    return [
        "## Where the rest of the documentation lives",
        "",
        f"- `{_HISTORICAL_INDEX}` — every document in `information/`, its status "
        "(current, historical, or superseded), and what it may still be cited for.",
        f"- `{_RETENTION_POLICY}` — which generated trees are canonical evidence, which "
        "are disposable cache, and what has to exist before anything is deleted.",
        "- `information/DENDRITE_EFFECT_AUDIT_2026-08-30.md` — the current scientific "
        "verdict on whether dendrites beat noise and more training.",
        "- `information/audit/` — the cleanup audit and its priority ledger.",
        "",
        "Historical run reports keep their original numbers on purpose. When they "
        "disagree with this file, this file is the current state and they are evidence "
        "of what was true when they were written.",
        "",
    ]


def render_current_guide() -> str:
    """Render the whole generated guide as markdown text."""
    header = [
        GENERATED_BANNER,
        "",
        "# Current state guide",
        "",
        textwrap.fill(
            "This benchmark exists to answer one question: do dendrites (PerforatedAI "
            "perforated backpropagation) make a model hold up better under "
            "quantization than the same model without them? Everything below is "
            "generated from the code that runs the experiment, so it describes what "
            "the repository does today rather than what an earlier run did.",
            width=88,
        ),
        "",
        "Regenerate with `uv run dqb docs`; verify in CI with `uv run dqb docs --check`.",
        "",
        "Sources of truth: `src/dendritic_benchmark/specs.py`, `model_adapters.py`, "
        "`artifacts.py`, `statistics.py`, and the `cli.py` option registry.",
        "",
    ]
    sections = (
        header
        + _model_roster_section()
        + _condition_section()
        + _validity_section()
        + _cli_section()
        + _documentation_map_section()
    )
    return "\n".join(sections).rstrip() + "\n"


def write_current_guide(path: Path = CURRENT_GUIDE_PATH) -> Path:
    """Write the generated guide, creating its directory if needed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_current_guide())
    return path


def current_guide_is_current(path: Path = CURRENT_GUIDE_PATH) -> bool:
    """Whether the checked-in guide still matches the registries."""
    try:
        return path.read_text() == render_current_guide()
    except OSError:
        return False
